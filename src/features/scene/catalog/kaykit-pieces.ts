function kaykitPieces(
  folder: string,
  category: PieceCategory,
  specs: readonly KaykitSpec[],
): CatalogEntry[] {
  return specs.flatMap(({ category: own, ...spec }) =>
    genericPieces(folder, own ?? category, [spec]),
  );
}

